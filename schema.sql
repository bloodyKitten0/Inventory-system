INSERT INTO role_permissions (role_id, permission_id)
SELECT r.role_id, p.permission_id
FROM roles r
JOIN permissions p
  ON (r.name = 'Owner')
  OR (r.name = 'Product Manager'   AND p.name LIKE 'product.%')
  OR (r.name = 'Category Manager'  AND p.name LIKE 'category.%')
  OR (r.name = 'Customer Manager'  AND p.name LIKE 'customer.%')
  OR (r.name = 'Supplier Manager'  AND (p.name LIKE 'supplier.%' OR p.name LIKE 'product\_supplier.%'))
  OR (r.name = 'Warehouse Manager' AND p.name LIKE 'warehouse.%')
  OR (r.name = 'Inventory Manager' AND (p.name LIKE 'inventory.%' OR p.name = 'stock_movement.read'))
  OR (r.name = 'Ordering Manager'  AND (p.name LIKE 'order.%' OR p.name LIKE 'order\_item.%'))
  OR (r.name = 'Customer'          AND p.name IN ('product.read', 'category.read'))
ON CONFLICT DO NOTHING;

